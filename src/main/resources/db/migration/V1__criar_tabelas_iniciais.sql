CREATE TABLE eventos (
                         id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                         nome VARCHAR(150) NOT NULL,
                         descricao TEXT,
                         local VARCHAR(200) NOT NULL,
                         data_inicio TIMESTAMPTZ NOT NULL,
                         prazo_inscricao TIMESTAMPTZ NOT NULL,
                         capacidade INTEGER NOT NULL,
                         criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

                         CONSTRAINT ck_eventos_capacidade
                             CHECK (capacidade > 0),

                         CONSTRAINT ck_eventos_prazo
                             CHECK (prazo_inscricao <= data_inicio)
);

CREATE TABLE participantes (
                               id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                               nome VARCHAR(150) NOT NULL,
                               email VARCHAR(254) NOT NULL,
                               criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

                               CONSTRAINT uk_participantes_email UNIQUE (email)
);

CREATE TABLE inscricoes (
                            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                            evento_id BIGINT NOT NULL,
                            participante_id BIGINT NOT NULL,
                            status VARCHAR(20) NOT NULL DEFAULT 'CONFIRMADA',
                            data_inscricao TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                            atualizado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

                            CONSTRAINT fk_inscricoes_evento
                                FOREIGN KEY (evento_id)
                                    REFERENCES eventos (id)
                                    ON DELETE RESTRICT,

                            CONSTRAINT fk_inscricoes_participante
                                FOREIGN KEY (participante_id)
                                    REFERENCES participantes (id)
                                    ON DELETE RESTRICT,

                            CONSTRAINT uk_inscricoes_evento_participante
                                UNIQUE (evento_id, participante_id),

                            CONSTRAINT ck_inscricoes_status
                                CHECK (status IN ('CONFIRMADA', 'CANCELADA'))
);

CREATE INDEX idx_eventos_data_inicio
    ON eventos (data_inicio);

CREATE INDEX idx_inscricoes_evento_status
    ON inscricoes (evento_id, status);

CREATE INDEX idx_inscricoes_participante
    ON inscricoes (participante_id);